uint16_t protocol_crc16(const uint8_t *data, uint16_t len)
{
  uint16_t crc = 0xFFFFU;
  uint16_t i;
  for (i = 0U; i < len; i++)
    crc = (uint16_t)((crc >> 8) ^ crc16_tab[(crc ^ data[i]) & 0xFFU]);
  return crc;
}

uint16_t protocol_build_frame(uint8_t cmd, uint8_t src, uint8_t dst, uint8_t seq,
                              const uint8_t *payload, uint16_t len,
                              uint8_t *out, uint16_t out_size)
{
  uint16_t n = 0U;
  uint16_t crc;
  uint16_t i;
  if (len > PROTO_MAX_PAYLOAD) return 0U;
  if (out_size < PROTO_MAX_FRAME) return 0U;

  out[n++] = PROTO_HEAD0;
  out[n++] = PROTO_HEAD1;
  out[n++] = cmd;
  out[n++] = src;
  out[n++] = dst;
  out[n++] = (uint8_t)(len >> 8);
  out[n++] = (uint8_t)(len & 0xFFU);
  out[n++] = seq;
  if ((payload != 0) && (len != 0U))
  {
    for (i = 0U; i < len; i++) out[n++] = payload[i];
  }
  crc = protocol_crc16(&out[2], (uint16_t)(n - 2U));
  out[n++] = (uint8_t)(crc >> 8);
  out[n++] = (uint8_t)(crc & 0xFFU);
  out[n++] = PROTO_TAIL0;
  out[n++] = PROTO_TAIL1;
  return n;
}

int protocol_check_frame(const uint8_t *buf, uint16_t len, proto_frame_t *frame)
{
  uint16_t crc, ccrc;
  uint16_t i;

  if (len < 11U) return -1;
  if (buf[0] != PROTO_HEAD0 || buf[1] != PROTO_HEAD1) return -1;
  if (buf[len - 2U] != PROTO_TAIL0 || buf[len - 1U] != PROTO_TAIL1) return -1;

  frame->cmd = buf[2];
  frame->src = buf[3];
  frame->dst = buf[4];
  frame->len = (uint16_t)((uint16_t)buf[5] << 8 | buf[6]);
  frame->seq = buf[7];
  if (frame->len > PROTO_MAX_PAYLOAD) return -2;
  if ((uint16_t)(8U + frame->len + 2U + 2U) != len) return -3;

  ccrc = (uint16_t)((uint16_t)buf[8U + frame->len] << 8 | buf[9U + frame->len]);
  crc  = protocol_crc16(&buf[2], (uint16_t)(6U + frame->len));
  if (ccrc != crc) return -4;

  for (i = 0U; i < frame->len; i++)
    frame->payload[i] = buf[8U + i];
  return 0;
}

uint16_t protocol_pack_sensor(const proto_sensor_payload_t *s, uint8_t *out)
{
  out[0] = (uint8_t)(s->temp_x10 >> 8);  out[1] = (uint8_t)(s->temp_x10 & 0xFFU);
  out[2] = (uint8_t)(s->humi_x10 >> 8);  out[3] = (uint8_t)(s->humi_x10 & 0xFFU);
  out[4] = (uint8_t)(s->co2_ppm >> 8);   out[5] = (uint8_t)(s->co2_ppm & 0xFFU);
  out[6] = (uint8_t)(s->light_lux >> 8); out[7] = (uint8_t)(s->light_lux & 0xFFU);
  out[8] = s->soil_grade;
  out[9] = s->alarm_flags;
  return 10U;
}

int protocol_unpack_sensor(const uint8_t *pl, uint16_t len, proto_sensor_payload_t *s)
{
  if (len < 10U) return -1;
  s->temp_x10   = (uint16_t)((uint16_t)pl[0] << 8 | pl[1]);
  s->humi_x10   = (uint16_t)((uint16_t)pl[2] << 8 | pl[3]);
  s->co2_ppm    = (uint16_t)((uint16_t)pl[4] << 8 | pl[5]);
  s->light_lux  = (uint16_t)((uint16_t)pl[6] << 8 | pl[7]);
  s->soil_grade = pl[8];
  s->alarm_flags= pl[9];
  return 0;
}
